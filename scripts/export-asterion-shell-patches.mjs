import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const auditPath = path.join(root, 'docs/current/audits/asterion-shells/asterion-shell-geometry-audit.json');
const outputPath = path.join(root, 'src/xr/furnace/asterionShellPatchData.js');
const audit = JSON.parse(await fs.readFile(auditPath, 'utf8'));
const patches = audit.shells.map(({ assetId, layout, segments2d }) => ({
  assetId, face: layout.face, rotationDegrees: layout.rotationDegrees, scale: layout.scale,
  flipU: layout.flipU, flipV: layout.flipV, segments2d
}));
const source = `// Generated by scripts/export-asterion-shell-patches.mjs from the final geometry audit.\n` +
  `// Do not edit by hand. Runtime intentionally contains no audit diagnostics.\n` +
  `export const ASTERION_SHELL_PATCHES = Object.freeze(${JSON.stringify(patches, null, 2)});\n`;
await fs.writeFile(outputPath, source);
console.log(`Exported ${patches.length} Asterion patches → ${path.relative(root, outputPath)}`);
